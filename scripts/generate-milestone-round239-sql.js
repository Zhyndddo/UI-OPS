#!/usr/bin/env node
// Round 240 — SQL-file alternative to scripts/import-milestone-round239-csv.js
// --confirm, for whoever prefers pasting a plain .sql file into the
// Supabase SQL editor over running Node with live service-role
// credentials in a terminal (matches this repo's usual "SQL migration ->
// sql/pending/ -> team runs it manually" convention — see
// DATA_FIXES.md's standing workflow notes). Same transform, same result;
// this just emits it as SQL text instead of executing it directly.
//
// Reuses buildImportPayload()/CUTOFF_DATE from
// import-milestone-round239-csv.js rather than re-implementing the CSV
// parse/repair/CHART_MAP/dedupe logic a second time — one transform, two
// ways to apply it, so they can't drift out of sync with each other.
//
// Usage (no Supabase credentials needed — this only reads the CSV and
// writes a .sql file, it never talks to the database):
//   node scripts/generate-milestone-round239-sql.js "<path-to-csv>" [outFile]
//
// The generated file starts with a DELETE scoped to entry_date <=
// CUTOFF_DATE (2026-08-26), then INSERT ... ON CONFLICT ... DO UPDATE
// batches of 500 rows each, matching the live script's own upsert
// semantics and natural key (chart, track_title, artist, entry_date).
// Wrapped in BEGIN/COMMIT so a mid-run failure rolls back cleanly instead
// of leaving the table half-wiped, half-reinstated.

const fs = require("fs");
const { buildImportPayload, printReport, CUTOFF_DATE } = require("./import-milestone-round239-csv");

function sqlStr(v) {
  if (v == null) return "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function main() {
  const filePath = process.argv[2];
  const outFile = process.argv[3] || "sql/pending/round240-milestone-wipe-reinstate.sql";
  if (!filePath) {
    console.error('Usage: node scripts/generate-milestone-round239-sql.js "<path-to-csv>" [outFile]');
    process.exit(1);
  }

  const csvText = fs.readFileSync(filePath, "utf8");
  const result = buildImportPayload(csvText);
  printReport(result, /* confirm */ true); // same console report as the live script, framed as what this SQL file will do

  const { dedupedPayload } = result;
  const lines = [];
  lines.push(`-- Round 239/240 — Milestone log wipe-and-reinstate from the team's CSV export.`);
  lines.push(`-- Generated by scripts/generate-milestone-round239-sql.js — do not hand-edit;`);
  lines.push(`-- re-run the generator against an updated CSV instead if anything needs to change.`);
  lines.push(`-- ${dedupedPayload.length} row(s), entry_date <= ${CUTOFF_DATE} only. Rows after that date`);
  lines.push(`-- (the app's own post-27/8/2026 data) are never touched by this file.`);
  lines.push("");
  lines.push("BEGIN;");
  lines.push("");
  lines.push(`DELETE FROM milestone_chart_entries WHERE entry_date <= '${CUTOFF_DATE}';`);
  lines.push("");

  const CHUNK = 500;
  for (let i = 0; i < dedupedPayload.length; i += CHUNK) {
    const chunk = dedupedPayload.slice(i, i + CHUNK);
    const values = chunk.map((p) =>
      `  (${sqlStr(p.chart)}, ${sqlStr(p.platform)}, ${sqlStr(p.entry_date)}, ${sqlStr(p.track_title)}, ${sqlStr(p.artist)}, ${p.rank}, ${sqlStr(p.did)})`
    );
    lines.push(`INSERT INTO milestone_chart_entries (chart, platform, entry_date, track_title, artist, rank, did) VALUES`);
    lines.push(values.join(",\n") + "");
    lines.push(`ON CONFLICT (chart, track_title, artist, entry_date) DO UPDATE SET`);
    lines.push(`  platform = excluded.platform, rank = excluded.rank, did = excluded.did;`);
    lines.push("");
  }

  lines.push("COMMIT;");
  lines.push("");

  fs.mkdirSync(require("path").dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join("\n"), "utf8");
  console.log(`Wrote ${outFile} (${dedupedPayload.length} rows, ${Math.ceil(dedupedPayload.length / CHUNK)} INSERT batch(es)).`);
}

main();
